const items = Array.from({ length: 1000 }, (_, i) => {
  const id = i + 1;
  const descIndex = i % descriptions.length;

  // 이미지: Picsum (안정적)
  // 종횡비 약 0.4613 (세로형) 유지를 위한 랜덤 크기 지정
  const width = Math.floor(Math.random() * 300) + 300; // 300 ~ 599
  const height = Math.round(width / 0.4613);
  const thumbnail = `https://picsum.photos/id/${id % 100}/${width}/${height}`;

  /**
   * 비디오: 403 에러 방지를 위한 안정적인 오픈 소스 MP4
   * 아래 링크들은 테스트용으로 널리 쓰이는 표준 MP4 파일들입니다.
   */
  const videoSources = [
    "https://www.w3schools.com/html/mov_bbb.mp4",
    "https://interactive-examples.mdn.mozilla.net/media/cc0-videos/friday.mp4",
    "https://interactive-examples.mdn.mozilla.net/media/cc0-videos/flower.mp4",
    "https://media.w3.org/2010/05/sintel/trailer.mp4",
    "https://media.w3.org/2010/05/bunny/trailer.mp4",
    "https://www.w3schools.com/html/broken_video_404_test.mp4",
    ""
  ];
  // 50% 확률로 영상/이미지 구분
  const videoUrl = Math.random() > 0.5 ? videoSources[i % videoSources.length] : null;

  let description = descriptions[descIndex];
  if (i % 15 === 0) {
    description = (descriptions[descIndex] + " ").repeat(8);
  }

  const title = i % 20 === 0 ? null : titles[descIndex];

  return {
    id: id.toString(),
    title: title,
    description: description,
    tags: tagsList[descIndex],
    thumbnail: videoUrl != null ? null : thumbnail,
    videoUrl: videoUrl,
    status: statuses[id % 4],
    category: categories[id % 4],
    createdAt: new Date(Date.now() - id * 3600000).toISOString(),
    likes: Math.floor(Math.random() * 500),
    views: Math.floor(Math.random() * 5000)
  };
});

